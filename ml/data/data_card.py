"""Render docs/data_card.md from ml/data/stats.json. Run: python -m ml.data.data_card"""
import json
import re

from ml.data.download import ROOT
from ml.data.prepare import STATS_JSON
from ml.training.features import DISEASES, FAIRNESS_ONLY, TARGETS

OUT = ROOT / "docs" / "data_card.md"

LIMITATIONS = [
    "US population, 2014/2015; not validated on Indian users.",
    "Smokeless tobacco (gutka, khaini) and bidis, common in India, are not captured; `Smoker` is "
    "\"ever smoked 100 cigarettes\" and cannot return to 0 after quitting.",
    "BMI risk thresholds differ for South Asians; the model uses raw BMI, guidance uses Asian cut-offs.",
    "Sex is binary in the data; there is no data for intersex or non-binary people.",
    "Survey weights are not in the cleaned file, so prevalence here is not nationally representative.",
    "Answers are self-reported and can be wrong; \"ever told\" labels exclude undiagnosed people "
    "(label noise, likely under-counting cases).",
    "Cross-sectional survey: labels describe conditions people already have, so the models estimate "
    "similarity to people with the condition, not future risk. Some answers (e.g. general health, "
    "difficulty walking, physical activity) may be consequences of the condition, not causes.",
    "`Diabetes_binary` merges prediabetes with diabetes; the models cannot tell them apart.",
    "`HeartDiseaseorAttack` merges coronary heart disease and heart attack.",
    "Age is only available in 5-year bands (13 bands, 80+ open-ended); BMI is rounded to an integer.",
    "Source year is inconsistent between sources: the Kaggle page and file name say BRFSS 2015, while "
    "the UCI page links CDC's BRFSS 2014 annual data page. We treat it as BRFSS 2015 (the file name) "
    "and record the discrepancy.",
    "The cleaning done by the Kaggle author (dropping rows with missing answers, recoding) is not "
    "fully documented, so people who skipped questions are excluded in an unknown way.",
]

FEATURE_ROWS = re.compile(r"^\| `(\w+)` \|.*$", re.M)


def main() -> None:
    s = json.loads(STATS_JSON.read_text())
    spec = (ROOT / "docs" / "SPEC.md").read_text(encoding="utf-8")
    sec = spec.split("### 3.3")[1].split("Optional separate symptom")[0]
    feature_table = "\n".join(
        ["| Feature | Question shown to user | Type / values | Validation |", "|---|---|---|---|"]
        + [m.group(0) for m in FEATURE_ROWS.finditer(sec)]
    )
    n = s["rows"]
    prev = "\n".join(
        f"| `{d}` | `{TARGETS[d]}` | {s['positives'][d]:,} | {s['prevalence'][d]:.2%} |" for d in DISEASES
    )
    splits = "\n".join(
        f"| {d} | " + " | ".join(f"{s['splits'][d][k]['n']:,} ({s['splits'][d][k]['prevalence']:.2%})"
                                  for k in ("train", "cal_a", "cal_b", "test")) + " |"
        for d in DISEASES
    )
    ov = s["label_overlap"]
    figs = "\n\n".join(f"![{f.split('/')[-1]}](figures/{f.split('/')[-1]})" for f in s["figures"])
    lim = "\n".join(f"{i}. {t}" for i, t in enumerate(LIMITATIONS, 1))
    bmi = s["distributions"]["BMI"]

    OUT.write_text(f"""# Data card — CDC BRFSS Diabetes Health Indicators

*Generated by `python -m ml.data.data_card` from `ml/data/stats.json`. Do not edit by hand.*

## Source

| | |
|---|---|
| Name | CDC Diabetes Health Indicators (UCI ML Repository id 891) |
| DOI | 10.24432/C53919 — <https://doi.org/10.24432/C53919> |
| Citation (UCI) | "CDC Diabetes Health Indicators [Dataset]. (2017). UCI Machine Learning Repository. https://doi.org/10.24432/C53919." |
| Same data on Kaggle | `alexteboul/diabetes-health-indicators-dataset`, file `diabetes_binary_health_indicators_BRFSS2015.csv` |
| Underlying survey | US CDC Behavioral Risk Factor Surveillance System (BRFSS), funded by the CDC |
| File used | `data/raw/diabetes_binary_health_indicators_BRFSS2015.csv` (downloaded by `python -m ml.data.download`, git-ignored) |
| Prepared file hash (SHA-256) | `{s['data_hash']}` |

### Licence

- UCI page, licence field, verbatim: **"See linked dataset for licensing information."** (links to the Kaggle page).
- Kaggle dataset licence field (read from the Kaggle API, `licenseName`), verbatim: **"CC0: Public Domain"**.
- The underlying BRFSS data is US federal (CDC) public survey data.

Finding: licence is **CC0: Public Domain** as stated by the Kaggle publisher. We have not seen a separate
CDC licence statement for this derived file. UCI asks users to follow the acknowledgement policy of the
original dataset site.

## How the data was collected

BRFSS is an annual **telephone survey** (landline and mobile) of US adults. All answers are
**self-reported**. The cleaned file has one row per respondent, 21 inputs + label, no missing values
(rows with missing answers were dropped by the Kaggle author). Survey weights are not included.

## What the labels mean

| Disease key | Column | Meaning (BRFSS wording) | Positives | Prevalence (unweighted) |
|---|---|---|---|---|
{prev}

Labels are **"ever told / ever had"**, from a single cross-sectional survey. They describe whether
a person has *already* been told they have the condition — not future risk.

Label overlap: diabetes & heart {ov['diabetes_and_heart']:,} · diabetes & stroke {ov['diabetes_and_stroke']:,} ·
heart & stroke {ov['heart_and_stroke']:,}. No label is used as an input to any model (D-19).

## Size and duplicates

- Rows: **{n:,}**
- Exact duplicate rows (all 22 columns): **{s['exact_duplicate_rows']:,}** ({s['exact_duplicate_rows'] / n:.1%})
- Duplicates on the 14 model inputs only: **{s['duplicate_rows_on_14_features']:,}** ({s['duplicate_rows_on_14_features'] / n:.1%})

Duplicates are kept (the answers are coarse, so different people can give identical answers).
Phase 3 also reports test metrics on a de-duplicated test set as a robustness check (SPEC §3.4).

## Splits

Per disease, stratified on that disease's label, seed 42: train 60% / calibration 20% / test 20%;
calibration is halved into cal-A (isotonic calibration) and cal-B (thresholds, conformal).
Row indices (not data) are in `ml/data/splits/<disease>.json`. Format: n (prevalence).

| Disease | train | cal-A | cal-B | test |
|---|---|---|---|---|
{splits}

## Features (model inputs, SPEC §3.3)

{feature_table}

BMI in the file: 1st percentile {bmi['0.01']:.0f}, median {bmi['0.5']:.0f}, 99th percentile {bmi['0.99']:.0f},
max {s['ranges']['BMI'][1]}. {s['bmi_over_70']:,} rows have BMI > 70, which the app's validation (12–70)
would reject; they are kept in training as recorded.

## Fairness-only columns (never model inputs, never asked in the app — D-6)

{", ".join(f"`{c}`" for c in FAIRNESS_ONLY)}. Used only to audit model behaviour across groups (SPEC §4.7).

## Limitations

{lim}

## Exploratory analysis

{figs}

Rates rise steeply with age band and with worse self-rated general health for all three labels.
These are associations in survey data, not causes.

## Other data

The Pune Clinical Risk Synthetic Dataset (`data/synthetic/`) is synthetic. It is used only for demo
profiles and stress tests and never to train or evaluate the models (D-4).
""", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
