"""Experiment (not applied): per-age-group t_mod so each age group gets recall >= 0.80 on cal-B.

Run: python -m ml.training.mitigation  -> docs/fairness_mitigation.md
Saved artifacts are not changed; the team decides whether to adopt it (SPEC §4.7).
"""
import json

import numpy as np
import pandas as pd

from ml.data.download import ROOT
from ml.data.prepare import PROCESSED, SPLITS_DIR
from ml.predictor import DiseaseModel
from ml.training import bands
from ml.training.features import DISEASES, TARGETS

OUT = ROOT / "docs" / "fairness_mitigation.md"
AGE_GROUPS = {"18-39": (1, 4), "40-59": (5, 8), "60+": (9, 13)}


def age_group(age_band: pd.Series) -> np.ndarray:
    out = np.empty(len(age_band), dtype=object)
    for g, (lo, hi) in AGE_GROUPS.items():
        out[age_band.between(lo, hi).to_numpy()] = g
    return out


def per_group(y, p, g, t_of_group, t_high):
    rows = {}
    flagged = p >= np.array([t_of_group[x] for x in g])
    for name in AGE_GROUPS:
        m = g == name
        yy, ff = y[m], flagged[m]
        rows[name] = {"recall": ff[yy == 1].mean(), "fpr": ff[yy == 0].mean(), "flagged": ff.mean(),
                      "t_mod": t_of_group[name]}
    rows["all"] = {"recall": flagged[y == 1].mean(), "fpr": flagged[y == 0].mean(),
                   "flagged": flagged.mean(), "t_mod": None}
    return rows


def main() -> None:
    df = pd.read_parquet(PROCESSED)
    lines = ["# Fairness mitigation experiment — per-age-group t_mod (not applied)", "",
             "*Generated by `python -m ml.training.mitigation`. Thresholds fitted on cal-B, results on test.*",
             "", "Each age group gets its own t_mod = largest threshold with recall >= 0.80 **within that group** "
             "on cal-B. t_high is unchanged. Flagged = moderate or high band.", ""]
    for d in DISEASES:
        m = DiseaseModel(d)
        s = json.loads((SPLITS_DIR / f"{d}.json").read_text())
        y = df[TARGETS[d]].to_numpy()
        res = {}
        for split in ("cal_b", "test"):
            rows = df.iloc[s[split]]
            res[split] = (y[s[split]], m.predict(rows)["p"], age_group(rows["Age"]))
        yb, pb, gb = res["cal_b"]
        t_group = {}
        for name in AGE_GROUPS:
            mask = gb == name
            t = bands.thresholds(pb[mask], yb[mask])["t_mod"]
            t_group[name] = min(t, m.t_high)  # keep t_mod <= t_high
        yt, pt, gt = res["test"]
        before = per_group(yt, pt, gt, {k: m.t_mod for k in AGE_GROUPS}, m.t_high)
        after = per_group(yt, pt, gt, t_group, m.t_high)
        lines += [f"## {d}", "",
                  "| Group | t_mod before → after | recall before → after | false-positive rate before → after | flagged share before → after |",
                  "|---|---|---|---|---|"]
        for g in [*AGE_GROUPS, "all"]:
            b, a = before[g], after[g]
            t = "—" if a["t_mod"] is None else f"{b['t_mod']:.3f} → {a['t_mod']:.3f}"
            lines.append(f"| {g} | {t} | {b['recall']:.3f} → {a['recall']:.3f} | {b['fpr']:.3f} → {a['fpr']:.3f} "
                         f"| {b['flagged']:.1%} → {a['flagged']:.1%} |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
